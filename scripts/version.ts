// One version for the whole product. The root package.json is the source of truth; `set` copies it to the
// workspace packages and to android/version.properties, `verify` is the release gate in CI.
//
//   bun scripts/version.ts show
//   bun scripts/version.ts set 0.2.0          (or 0.2.0-rc.1, 0.2.0-beta.3)
//   bun scripts/version.ts verify v0.2.0      (fails unless every file agrees with the tag)
//   bun scripts/version.ts meta               (key=value lines for CI: version, prerelease, android_version_code)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export type Semver = { major: number; minor: number; patch: number; pre: { label: "beta" | "rc"; n: number } | null };

const RE = /^(\d+)\.(\d+)\.(\d+)(?:-(beta|rc)\.(\d+))?$/;

export function parseSemver(input: string): Semver {
  const m = RE.exec(input.replace(/^v/, ""));
  if (!m) throw new Error(`"${input}" is not a version like 1.2.3, 1.2.3-rc.1 or 1.2.3-beta.2`);
  const [major, minor, patch] = [Number(m[1]), Number(m[2]), Number(m[3])];
  if (minor > 99 || patch > 99 || major > 2000) throw new Error("minor and patch must be 0-99 and major at most 2000 (Android versionCode limit)");
  return { major, minor, patch, pre: m[4] ? { label: m[4] as "beta" | "rc", n: Number(m[5]) } : null };
}

/**
 * Android needs a number that only grows. major*1_000_000 + minor*10_000 + patch*100 + a 0-99 slot:
 * betas use 1-49, release candidates 50-98, the final release 99, so 1.2.3-rc.1 < 1.2.3.
 */
export function androidVersionCode(v: string): number {
  const s = parseSemver(v);
  let slot = 99;
  if (s.pre) {
    if (s.pre.n < 1 || s.pre.n > 48) throw new Error("pre-release number must be 1-48");
    slot = s.pre.label === "beta" ? s.pre.n : 50 + s.pre.n;
  }
  return s.major * 1_000_000 + s.minor * 10_000 + s.patch * 100 + slot;
}

const PACKAGES = ["package.json", "backend/package.json", "shared/package.json", "web/package.json"];
const ANDROID = "android/version.properties";

function readJson(path: string): Record<string, unknown> { return JSON.parse(readFileSync(path, "utf8")); }

export function androidProps(v: string): string {
  return `# Generated by scripts/version.ts. Do not edit by hand.\nversionName=${v}\nversionCode=${androidVersionCode(v)}\n`;
}

export function setVersion(root: string, v: string): void {
  parseSemver(v);
  for (const p of PACKAGES) {
    const file = join(root, p);
    const json = readJson(file);
    json.version = v;
    writeFileSync(file, JSON.stringify(json, null, 2) + "\n");
  }
  writeFileSync(join(root, ANDROID), androidProps(v));
}

/** Returns a list of problems; empty means every file carries exactly `expected`. */
export function verifyVersion(root: string, expected: string): string[] {
  const want = expected.replace(/^v/, "");
  const problems: string[] = [];
  try { parseSemver(want); } catch (e) { return [(e as Error).message]; }
  for (const p of PACKAGES) {
    const got = readJson(join(root, p)).version;
    if (got !== want) problems.push(`${p} has version ${JSON.stringify(got)}, expected ${want}`);
  }
  let props = "";
  try { props = readFileSync(join(root, ANDROID), "utf8"); } catch { problems.push(`${ANDROID} is missing`); }
  if (props && props !== androidProps(want)) problems.push(`${ANDROID} does not match ${want} (run: bun scripts/version.ts set ${want})`);
  return problems;
}

export function meta(root: string): Record<string, string> {
  const v = String(readJson(join(root, "package.json")).version);
  const s = parseSemver(v);
  return { version: v, prerelease: String(s.pre !== null), android_version_code: String(androidVersionCode(v)) };
}

if (import.meta.main) {
  const root = join(import.meta.dir, "..");
  const [cmd, arg] = process.argv.slice(2);
  try {
    if (cmd === "show") console.log(String(readJson(join(root, "package.json")).version));
    else if (cmd === "set" && arg) { setVersion(root, arg.replace(/^v/, "")); console.log(`Version set to ${arg.replace(/^v/, "")}. Commit it, then tag v${arg.replace(/^v/, "")}.`); }
    else if (cmd === "verify" && arg) {
      const problems = verifyVersion(root, arg);
      if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
      console.log(`All files are at ${arg.replace(/^v/, "")}.`);
    } else if (cmd === "meta") for (const [k, v] of Object.entries(meta(root))) console.log(`${k}=${v}`);
    else { console.error("usage: version.ts show | set <version> | verify <tag> | meta"); process.exit(2); }
  } catch (e) { console.error((e as Error).message); process.exit(1); }
}
